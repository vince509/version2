"use strict";

const { neon } = require("@neondatabase/serverless");

function normalizeUser(user) {
    if (!user) return null;
    return {
        ...user,
        id: Number(user.id)
    };
}

class PostgresStore {
    constructor(databaseUrl) {
        this.sql = neon(databaseUrl);
        this.initialization = null;
        this.storageDescription = "Neon PostgreSQL";
        this.usesMongo = false;
    }

    async initialize() {
        if (!this.initialization) {
            this.initialization = this.createSchema().catch((error) => {
                this.initialization = null;
                throw error;
            });
        }
        await this.initialization;
    }

    async createSchema() {
        await this.sql`
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL,
                username_lower TEXT NOT NULL UNIQUE,
                password_salt TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL CHECK (role IN ('Student', 'Faculty', 'Admin')),
                google_sub TEXT UNIQUE,
                email TEXT,
                email_lower TEXT UNIQUE,
                created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
            )
        `;
        await this.sql`
            CREATE TABLE IF NOT EXISTS sessions (
                token_hash TEXT PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at BIGINT NOT NULL,
                idle_expires_at BIGINT NOT NULL,
                created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
            )
        `;
        await this.sql`CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires_at)`;
        await this.sql`
            CREATE TABLE IF NOT EXISTS papers (
                id TEXT PRIMARY KEY,
                title TEXT NOT NULL,
                title_lower TEXT NOT NULL,
                author TEXT NOT NULL,
                year INTEGER NOT NULL,
                topic TEXT NOT NULL,
                course TEXT NOT NULL,
                department TEXT NOT NULL,
                abstract TEXT NOT NULL,
                original_file_name TEXT NOT NULL,
                stored_file_name TEXT NOT NULL,
                created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
                status TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('pending', 'approved', 'rejected')),
                created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
                updated_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
            )
        `;
        await this.sql`CREATE INDEX IF NOT EXISTS papers_year ON papers(year DESC, title_lower)`;
        await this.sql`CREATE INDEX IF NOT EXISTS papers_status_created ON papers(status, created_at)`;
        await this.sql`CREATE INDEX IF NOT EXISTS papers_created_by ON papers(created_by, created_at DESC)`;
        await this.sql`
            CREATE TABLE IF NOT EXISTS app_migrations (
                id TEXT PRIMARY KEY,
                status TEXT NOT NULL,
                updated_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
            )
        `;
    }

    async close() {}

    async userCount() {
        const [result] = await this.sql`SELECT COUNT(*)::INTEGER AS count FROM users`;
        return result.count;
    }

    async adminCount() {
        const [result] = await this.sql`SELECT COUNT(*)::INTEGER AS count FROM users WHERE role = 'Admin'`;
        return result.count;
    }

    async getUserById(id) {
        const [user] = await this.sql`SELECT * FROM users WHERE id = ${Number(id)}`;
        return normalizeUser(user);
    }

    async getPublicUserById(id) {
        const [user] = await this.sql`
            SELECT id, username, role, created_at FROM users WHERE id = ${Number(id)}
        `;
        return normalizeUser(user);
    }

    async getUserByUsername(username) {
        const [user] = await this.sql`
            SELECT * FROM users WHERE username_lower = ${username.toLowerCase()}
        `;
        return normalizeUser(user);
    }

    async getUserByGoogleSub(sub) {
        const [user] = await this.sql`
            SELECT id, username, role, created_at FROM users WHERE google_sub = ${sub}
        `;
        return normalizeUser(user);
    }

    async getUserIdByEmail(email) {
        const [user] = await this.sql`
            SELECT id FROM users WHERE email_lower = ${email.toLowerCase()}
        `;
        return normalizeUser(user);
    }

    async createUser(userData) {
        try {
            const [user] = await this.sql`
                INSERT INTO users (
                    username, username_lower, password_salt, password_hash, role, google_sub, email, email_lower
                ) VALUES (
                    ${userData.username}, ${userData.username.toLowerCase()}, ${userData.password_salt},
                    ${userData.password_hash}, ${userData.role}, ${userData.google_sub || null},
                    ${userData.email || null}, ${userData.email ? userData.email.toLowerCase() : null}
                )
                RETURNING id, username, role, created_at
            `;
            return normalizeUser(user);
        } catch (error) {
            if (error.code === "23505") throw new Error("UNIQUE constraint failed: users.username");
            throw error;
        }
    }

    async updateUser(id, changes) {
        const numericId = Number(id);
        try {
            if (Object.prototype.hasOwnProperty.call(changes, "email")) {
                await this.sql`
                    UPDATE users SET email = ${changes.email}, email_lower = ${changes.email ? changes.email.toLowerCase() : null}
                    WHERE id = ${numericId}
                `;
            } else if (Object.prototype.hasOwnProperty.call(changes, "password_salt")) {
                await this.sql`
                    UPDATE users SET
                        username = ${changes.username}, username_lower = ${changes.username.toLowerCase()},
                        role = ${changes.role}, password_salt = ${changes.password_salt},
                        password_hash = ${changes.password_hash}
                    WHERE id = ${numericId}
                `;
            } else {
                await this.sql`
                    UPDATE users SET username = ${changes.username},
                        username_lower = ${changes.username.toLowerCase()}, role = ${changes.role}
                    WHERE id = ${numericId}
                `;
            }
        } catch (error) {
            if (error.code === "23505") throw new Error("UNIQUE constraint failed: users.username");
            throw error;
        }
        return this.getPublicUserById(numericId);
    }

    async listUsers() {
        return this.sql`SELECT id, username, role, created_at FROM users ORDER BY username_lower`;
    }

    async deleteUser(id) {
        await this.sql`DELETE FROM users WHERE id = ${Number(id)}`;
    }

    async getSessionWithUser(tokenHash) {
        const [session] = await this.sql`
            SELECT users.id, users.username, users.role, users.created_at,
                   sessions.expires_at, sessions.idle_expires_at
            FROM sessions JOIN users ON users.id = sessions.user_id
            WHERE sessions.token_hash = ${tokenHash}
        `;
        return normalizeUser(session);
    }

    async saveSession(tokenHash, userId, expiresAt, idleExpiresAt) {
        await this.sql`DELETE FROM sessions WHERE expires_at <= ${Date.now()}`;
        await this.sql`
            INSERT INTO sessions (token_hash, user_id, expires_at, idle_expires_at)
            VALUES (${tokenHash}, ${Number(userId)}, ${expiresAt}, ${idleExpiresAt})
        `;
    }

    async touchSession(tokenHash, idleExpiresAt) {
        await this.sql`
            UPDATE sessions SET idle_expires_at = ${idleExpiresAt} WHERE token_hash = ${tokenHash}
        `;
    }

    async deleteSession(tokenHash) {
        await this.sql`DELETE FROM sessions WHERE token_hash = ${tokenHash}`;
    }

    async listApprovedPapers() {
        return this.sql`
            SELECT id, title, author, year, topic, course, department, abstract,
                   original_file_name AS "fileName", created_at AS "createdAt", updated_at AS "updatedAt"
            FROM papers WHERE status = 'approved' ORDER BY year DESC, title_lower
        `;
    }

    async listSubmissions(userId) {
        return this.sql`
            SELECT id, title, author, year, topic, course, department, abstract,
                   original_file_name AS "fileName", status, created_at AS "createdAt"
            FROM papers WHERE created_by = ${Number(userId)} ORDER BY created_at DESC
        `;
    }

    async listPendingPapers() {
        return this.sql`
            SELECT papers.id, papers.title, papers.author, papers.year, papers.topic,
                   papers.course, papers.department, papers.abstract,
                   papers.original_file_name AS "fileName", papers.created_at AS "createdAt",
                   users.username AS "submittedBy"
            FROM papers LEFT JOIN users ON users.id = papers.created_by
            WHERE papers.status = 'pending' ORDER BY papers.created_at
        `;
    }

    async insertPaper(paper) {
        await this.sql`
            INSERT INTO papers (
                id, title, title_lower, author, year, topic, course, department, abstract,
                original_file_name, stored_file_name, created_by, status
            ) VALUES (
                ${paper.id}, ${paper.title}, ${paper.title_lower || paper.title.toLowerCase()},
                ${paper.author}, ${paper.year}, ${paper.topic}, ${paper.course}, ${paper.department},
                ${paper.abstract}, ${paper.original_file_name}, ${paper.stored_file_name},
                ${paper.created_by}, ${paper.status}
            )
        `;
    }

    async getPaper(id) {
        const [paper] = await this.sql`SELECT * FROM papers WHERE id = ${id}`;
        return paper || null;
    }

    async getPaperFile(id, status) {
        const [paper] = await this.sql`
            SELECT original_file_name, stored_file_name, status
            FROM papers WHERE id = ${id} AND status = ${status}
        `;
        return paper || null;
    }

    async updatePaper(id, changes) {
        if (Object.prototype.hasOwnProperty.call(changes, "status")) {
            await this.sql`
                UPDATE papers SET status = ${changes.status},
                    updated_at = to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
                WHERE id = ${id}
            `;
            return;
        }
        await this.sql`
            UPDATE papers SET
                title = ${changes.title}, title_lower = ${changes.title.toLowerCase()},
                author = ${changes.author}, year = ${changes.year}, topic = ${changes.topic},
                course = ${changes.course}, department = ${changes.department}, abstract = ${changes.abstract},
                original_file_name = ${changes.original_file_name},
                stored_file_name = ${changes.stored_file_name},
                updated_at = to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
            WHERE id = ${id}
        `;
    }

    async rejectPaper(id) {
        await this.sql`
            UPDATE papers SET status = 'rejected', stored_file_name = '',
                updated_at = to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
            WHERE id = ${id}
        `;
    }

    async deletePaper(id) {
        await this.sql`DELETE FROM papers WHERE id = ${id}`;
    }
}

function createPostgresStore(databaseUrl) {
    return new PostgresStore(databaseUrl);
}

module.exports = { createPostgresStore };
